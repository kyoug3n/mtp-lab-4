"""Средн. 4: факториал через ``functools.reduce``.

``reduce(f, [a, b, c], x)`` вычисляет ``f(f(f(x, a), b), c)`` — сворачивает
последовательность в одно значение слева направо. Факториал — свёртка
чисел 2, 3, …, n умножением.
"""
import operator
from functools import reduce

from funclab.checks import check_non_negative_int


def factorial(n: int) -> int:
    """n! = 1 · 2 · … · n.

    Решения в коде:

    * начальное значение 1 — это произведение пустого набора чисел. С ним
      ``range(2, 1)`` и ``range(2, 2)`` (случаи n = 0 и n = 1) дают 1 без
      отдельной ветки; без него ``reduce`` на пустом диапазоне бросил бы
      ``TypeError``;
    * диапазон начинается с 2: умножать на 1 бессмысленно;
    * ``operator.mul`` вместо ``lambda a, b: a * b`` — та же функция двух
      аргументов, но готовая и с именем в трассировке ошибки.

    Ограничение: умножения идут по одному слева направо, и накопленное
    произведение каждый раз умножается на очередное число. Это в разы
    медленнее ``math.factorial``, который перемножает числа попарно
    (разделяй и властвуй), и разрыв растёт вместе с n.

    >>> factorial(0), factorial(1), factorial(5)
    (1, 1, 120)
    >>> factorial(5.0)
    Traceback (most recent call last):
    ...
    TypeError: n: ожидалось целое число, получено 5.0

    :raises TypeError: если ``n`` не целое число (``bool`` тоже не
        принимается).
    :raises ValueError: если ``n`` отрицательное.
    """
    check_non_negative_int(n, "n")
    return reduce(operator.mul, range(2, n + 1), 1)
