"""Средн. 10: применить несколько функций к списку через ``map``.

Формулировку «применить несколько функций к списку» можно понять
по-разному:

* каждую функцию к каждому элементу — выбрано здесь;
* каждую функцию ко всему списку целиком (``sum``, ``max``, ``len``) —
  тогда ``map`` идёт по функциям, а список лишь аргумент, и поэлементной
  обработки нет;
* функции по цепочке, результат одной — вход следующей, — это уже
  композиция функций и конвейер, в варианте это отдельное задание
  (Повыш. 9).

Функции здесь — обычные данные: их кладут в кортеж и передают аргументом,
а внутренний ``map`` вызывает их по очереди.
"""
from collections.abc import Callable, Iterable, Iterator
from typing import Any, TypeVar

from funclab.checks import check_callable

T = TypeVar("T")


def map_all(
    functions: Iterable[Callable[[T], Any]], items: Iterable[T]
) -> Iterator[tuple[Any, ...]]:
    """Для каждого элемента — кортеж результатов всех функций.

    Внешний ``map`` идёт по элементам, внутренний — по функциям:
    элементу ``x`` соответствует ``(f1(x), f2(x), …)``. Результат ленивый,
    как и сам ``map``: функции вызываются, только когда строка нужна.

    Функции сразу собираются в кортеж: их нужно обойти для каждого
    элемента, а генератор функций кончился бы на первом. Элементы же
    обходятся один раз, поэтому ``items`` может быть одноразовым итератором
    и даже бесконечным генератором.

    >>> rows = map_all([abs, lambda x: x * x, str], [-2, 3])
    >>> list(rows)
    [(2, 4, '-2'), (3, 9, '3')]

    :raises TypeError: сразу при вызове, если среди ``functions`` есть
        не функция.
    """
    functions = tuple(functions)
    for position, function in enumerate(functions, start=1):
        check_callable(function, f"функция {position}")
    return map(
        lambda item: tuple(map(lambda function: function(item), functions)),
        items,
    )
