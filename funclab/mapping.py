"""Средн. 10: применить несколько функций к списку через ``map``.

Формулировку «применить несколько функций к списку» можно понять
по-разному:

1. каждую функцию к каждому элементу, результат сгруппирован по элементам:
   на элемент — кортеж ``(f1(x), f2(x), …)``. Выбрано здесь;
2. то же самое, но сгруппированное по функциям: на функцию — список
   ``list(map(f, items))``. Получается из первого транспонированием:
   ``zip(*map_all(functions, items))``;
3. каждую функцию ко всему списку целиком (``sum``, ``max``, ``len``) —
   тогда ``map`` идёт по функциям, а список только аргумент, и
   поэлементной обработки нет;
4. функции по цепочке, результат одной — вход следующей, — это уже
   композиция функций и конвейер, в варианте это отдельное задание
   (Повыш. 9).

Почему выбрана группировка по элементам: задание требует применить
функции именно через ``map``, а поэлементный обход — это и есть ``map``.
При такой группировке результат остаётся ленивым и работает на
одноразовых и бесконечных потоках, тогда как группировка по функциям
заставила бы прочитать все элементы для каждой функции. Обратный переход
стоит один ``zip``, прямой — нет.

Функции здесь — обычные данные: их кладут в кортеж и передают аргументом,
а внутренний ``map`` вызывает их по очереди.
"""
from collections.abc import Callable, Iterable, Iterator
from typing import Any, TypeVar

from funclab.checks import as_stream, check_callables

T = TypeVar("T")


def map_all(
    functions: Iterable[Callable[[T], Any]], items: Iterable[T]
) -> Iterator[tuple[Any, ...]]:
    """Для каждого элемента — кортеж результатов всех функций.

    Внешний ``map`` идёт по элементам, внутренний — по функциям:
    элементу ``x`` соответствует ``(f1(x), f2(x), …)``. Результат ленивый,
    как и сам ``map``: функции вызываются, только когда строка нужна.

    Функции сразу собираются в кортеж: их нужно обойти для каждого
    элемента, а генератор функций кончился бы на первом. Элементы же
    обходятся один раз, поэтому ``items`` может быть одноразовым итератором
    и даже бесконечным генератором.

    Оба аргумента проверяются при вызове, а не при первом ``next``: у
    ``items`` сразу берётся итератор, поэтому ``map_all([abs], 5)`` падает
    немедленно. Ленивы вычисления, а не проверка аргументов, и ровно так
    же устроен встроенный ``map``: ``map(abs, 5)`` тоже бросает
    ``TypeError`` в момент вызова. Ни одного элемента при этом не читается
    — ``iter`` бесконечного генератора ничего не вычисляет.

    >>> rows = map_all([abs, lambda x: x * x, str], [-2, 3])
    >>> list(rows)
    [(2, 4, '-2'), (3, 9, '3')]
    >>> list(zip(*map_all([abs, str], [-2, 3])))  # по функциям
    [(2, 3), ('-2', '3')]

    :raises TypeError: сразу при вызове, если ``functions`` или ``items``
        не итерируемые или если среди функций есть не функция.
    """
    prepared = tuple(as_stream(functions, "функции"))
    check_callables(prepared, "функция")
    return map(
        lambda item: tuple(map(lambda function: function(item), prepared)),
        as_stream(items, "элементы"),
    )
